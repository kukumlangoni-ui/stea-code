export function getCategoryIconAndDescription(categoryValue) {
  const id = getCategoryId(categoryValue);
  const label = formatCategoryName(categoryValue) || String(categoryValue || "").trim();

  // Check subcategory first
  const sub = getDeveloperSubcategory(categoryValue);
  if (sub) {
    return {
      icon: sub.icon || "💻",
      description: sub.description || `Discover useful ${sub.label} resources for developers.`
    };
  }

  const fallback = CATEGORY_FALLBACKS[id] || {};
  const builtIn = WEBSITE_CATEGORIES.find((category) => category.id === id);
  return {
    icon: builtIn?.icon || getCategoryIcon(label),
    description: fallback.description || `Discover useful ${label} websites curated by STEA.`
  };
}

