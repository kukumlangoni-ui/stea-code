export function normalizeCategory(value) {
  return String(value || "")
    .trim()
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export function getCategoryId(categoryValue) {
  const raw = String(categoryValue || "").trim();
  const normalized = normalizeCategory(raw);
  if (!normalized) return "";

  // Check built-in main categories
  for (const category of WEBSITE_CATEGORIES) {
    if (normalizeCategory(category.label) === normalized) return category.id;
    if (normalizeCategory(category.id) === normalized) return category.id;
    if ((category.aliases || []).some((alias) => normalizeCategory(alias) === normalized)) {
      return category.id;
    }
  }

  // Check developer subcategories (map them to developers parent category if queried as main category)
  for (const sub of DEVELOPER_SUBCATEGORIES) {
    if (normalizeCategory(sub.label) === normalized || normalizeCategory(sub.id) === normalized) {
      return "developers";
    }
    if ((sub.aliases || []).some((alias) => normalizeCategory(alias) === normalized)) {
      return "developers";
    }
  }

  return normalized;
}

export function getDeveloperSubcategoryId(subValue) {
  const raw = String(subValue || "").trim();
  const normalized = normalizeCategory(raw);
  if (!normalized) return "";

  for (const sub of DEVELOPER_SUBCATEGORIES) {
    if (normalizeCategory(sub.label) === normalized) return sub.id;
    if (normalizeCategory(sub.id) === normalized) return sub.id;
    if ((sub.aliases || []).some((alias) => normalizeCategory(alias) === normalized)) {
      return sub.id;
    }
  }

  return normalized;
}

export function isDeveloperCategory(value) {
  const id = getCategoryId(value);
  return id === "developers";
}

export function getDeveloperSubcategories() {
  return DEVELOPER_SUBCATEGORIES;
}

export function getDeveloperSubcategory(slugOrName) {
  const id = getDeveloperSubcategoryId(slugOrName);
  return DEVELOPER_SUBCATEGORIES.find((s) => s.id === id) || null;
}

export function formatDeveloperSubcategoryName(subValue) {
  const raw = String(subValue || "").trim();
  if (!raw) return "";
  const sub = getDeveloperSubcategory(raw);
  if (sub?.label) return sub.label;
  return raw
    .split(/[\s_-]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1).toLowerCase())
    .join(" ");
}

export function formatCategoryName(categoryValue) {
  const raw = String(categoryValue || "").trim();
  if (!raw) return "";
  const id = getCategoryId(raw);
  const builtIn = WEBSITE_CATEGORIES.find((category) => category.id === id);
  if (builtIn?.label) return builtIn.label;

  // Check subcategory
  const sub = getDeveloperSubcategory(raw);
  if (sub?.label) return sub.label;

  return raw
    .split(/[\s_-]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1).toLowerCase())
    .join(" ");
}

